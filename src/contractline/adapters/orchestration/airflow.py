"""Airflow adapter: one generated Dag per plan step (ADR-0017).

Dags are code generated from the plan; nobody edits them. Ingestion Dags run on
a schedule derived from the contract's freshness SLA; silver and gold Dags are
triggered by Airflow assets when their inputs change. Every task calls
``contractline run-step``: Airflow orchestrates, the compute layer does the work.
"""

from collections.abc import Iterable
from pathlib import Path

from contractline.core.plan import Step, StepKind

HEADER = "# Generated by `contractline dags` from contracts. Do not edit: regenerate.\n"


def _asset(logical_name: str) -> str:
    return f'Asset(name="{logical_name}", uri="contractline://{logical_name}")'


def build_dag_source(step: Step, steps_by_table: dict[str, Step], env: str, command: str) -> str:
    """Python source of the Dag for one step."""
    produced = [t for t in step.writes if not t.split(".")[0].endswith("_quarantine")]
    inputs = [t for t in step.reads if t in steps_by_table]
    if step.kind is StepKind.SILVER:
        # Silver follows its own bronze only; reference checks read whatever is current.
        inputs = [t for t in inputs if steps_by_table[t].kind is StepKind.INGEST]
    if step.schedule:
        schedule = repr(step.schedule)
    elif inputs:
        schedule = " | ".join(_asset(t) for t in inputs)
        schedule = f"({schedule})" if len(inputs) > 1 else schedule
    else:
        schedule = "None"
    tags = [f"{k}:{v}" for k, v in step.tags] + [f"layer:{step.kind}", f"env:{env}"]
    outlets = ", ".join(_asset(t) for t in produced)
    return (
        HEADER
        + f'''"""{step.kind} step {step.id}: reads {", ".join(step.reads)}."""

import pendulum
from airflow.providers.standard.operators.bash import BashOperator
from airflow.sdk import DAG, Asset

with DAG(
    dag_id="{step.id}",
    schedule={schedule},
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    tags={sorted(tags)!r},
):
    BashOperator(
        task_id="run",
        bash_command="{command} run-step {step.id} --env {env}",
        outlets=[{outlets}],
    )
'''
    )


def build_dags(steps: Iterable[Step], env: str, command: str = "contractline") -> dict[str, str]:
    """File name -> source, for every step."""
    steps = list(steps)
    by_table = {table: step for step in steps for table in step.writes}
    return {f"{step.id}.py": build_dag_source(step, by_table, env, command) for step in steps}


def write_dags(dags: dict[str, str], folder: Path) -> list[str]:
    """Write the Dags and remove generated Dags that no longer exist. Returns changes."""
    folder.mkdir(parents=True, exist_ok=True)
    changes = []
    for path in folder.glob("*.py"):
        if path.name not in dags and path.read_text().startswith(HEADER):
            path.unlink()
            changes.append(f"removed {path.name}")
    for name, source in sorted(dags.items()):
        target = folder / name
        if not target.exists() or target.read_text() != source:
            target.write_text(source)
            changes.append(f"wrote {name}")
    return changes


def find_stale_dags(dags: dict[str, str], folder: Path) -> list[str]:
    """Differences between the generated Dags and the folder, without writing."""
    problems = []
    existing = {p.name: p.read_text() for p in folder.glob("*.py")} if folder.exists() else {}
    for name, source in sorted(dags.items()):
        if existing.get(name) != source:
            problems.append(f"{name} is missing or out of date")
    for name, text in sorted(existing.items()):
        if name not in dags and text.startswith(HEADER):
            problems.append(f"{name} no longer matches any contract")
    return problems
