"""Databricks Asset Bundle resources generated from the plan (ADR-0019).

One job per plan step, running ``contractline run-step`` from the project's
wheel on serverless compute. Ingestion jobs run on the SLA-derived schedule;
silver and gold jobs start when their input tables change (table-update
triggers), the Databricks counterpart of Airflow assets.
"""

from contractline.core.plan import Step, StepKind

HEADER = "# Generated by `contractline bundle` from contracts. Do not edit: regenerate.\n"

_QUARTZ = {
    "*/15 * * * *": "0 0/15 * * * ?",
    "*/30 * * * *": "0 0/30 * * * ?",
    "0 * * * *": "0 0 * * * ?",
    "0 */2 * * *": "0 0 0/2 * * ?",
    "0 */6 * * *": "0 0 0/6 * * ?",
    "0 */12 * * *": "0 0 0/12 * * ?",
    "0 0 * * *": "0 0 0 * * ?",
}


def to_quartz(cron: str) -> str:
    """The plan's five-field cron as Databricks' Quartz syntax."""
    try:
        return _QUARTZ[cron]
    except KeyError:
        raise ValueError(f"no Quartz equivalent for {cron!r}") from None


def _uc_name(logical: str, target_var: str = "${bundle.target}") -> str:
    """Logical names carry the environment as a prefix; the bundle target supplies it."""
    catalog, schema, table = logical.split(".")
    layer = catalog.split("_", 1)[1]
    return f"{target_var}_{layer}.{schema}.{table}"


def build_job(step: Step, steps_by_table: dict[str, Step]) -> str:
    inputs = [t for t in step.reads if t in steps_by_table]
    if step.kind is StepKind.SILVER:
        inputs = [t for t in inputs if steps_by_table[t].kind is StepKind.INGEST]
    lines = [
        f"    {step.id}:",
        f"      name: contractline-${{bundle.target}}-{step.id.replace('__', '-')}",
        "      max_concurrent_runs: 1",
        "      tags:",
        *[f'        {k}: "{v}"' for k, v in step.tags],
        f'        layer: "{step.kind}"',
    ]
    if step.schedule:
        lines += [
            "      schedule:",
            f'        quartz_cron_expression: "{to_quartz(step.schedule)}"',
            "        timezone_id: UTC",
            "        pause_status: ${var.schedule_pause_status}",
        ]
    elif inputs:
        lines += [
            "      trigger:",
            "        pause_status: ${var.schedule_pause_status}",
            "        table_update:",
            "          condition: ANY_UPDATED",
            "          table_names:",
            *[f"            - {_uc_name(t)}" for t in inputs],
        ]
    lines += [
        "      environments:",
        "        - environment_key: contractline",
        "          spec:",
        '            client: "2"',
        "            dependencies:",
        "              - ../dist/*.whl",
        "      tasks:",
        "        - task_key: run",
        "          environment_key: contractline",
        "          python_wheel_task:",
        "            package_name: contractline",
        "            entry_point: contractline",
        "            parameters:",
        "              - run-step",
        f"              - {step.id}",
        "              - --env",
        "              - ${bundle.target}",
        "              - --platform",
        "              - databricks",
        "              - --project",
        "              - ${workspace.file_path}/contracts",
        "              - --project",
        "              - ${workspace.file_path}/pipelines",
    ]
    return "\n".join(lines)


def build_bundle_resources(steps: list[Step]) -> str:
    by_table = {table: step for step in steps for table in step.writes}
    jobs = "\n".join(build_job(step, by_table) for step in steps)
    return HEADER + "resources:\n  jobs:\n" + jobs + "\n"
